import { HttpStatus } from '@nestjs/common';

/**
 * Mã lỗi nghiệp vụ dùng chung — khớp bảng 3.2 của docs/03-rest-api-design.md.
 */
export enum ErrorCode {
  INVALID_INPUT = 'INVALID_INPUT',
  OTP_INCORRECT = 'OTP_INCORRECT',
  UNAUTHENTICATED = 'UNAUTHENTICATED',
  FORBIDDEN = 'FORBIDDEN',
  NOT_FOUND = 'NOT_FOUND',
  FEE_ALREADY_PAID = 'FEE_ALREADY_PAID',
  OTP_ALREADY_USED = 'OTP_ALREADY_USED',
  IDEMPOTENCY_CONFLICT = 'IDEMPOTENCY_CONFLICT',
  OTP_EXPIRED = 'OTP_EXPIRED',
  INSUFFICIENT_BALANCE = 'INSUFFICIENT_BALANCE',
  TRANSACTION_INVALID_STATE = 'TRANSACTION_INVALID_STATE',
  RATE_LIMITED = 'RATE_LIMITED',
  INTERNAL_ERROR = 'INTERNAL_ERROR',
  DEPENDENCY_DOWN = 'DEPENDENCY_DOWN',
}

/** HTTP status mặc định cho mỗi mã lỗi. */
export const ERROR_HTTP_STATUS: Record<ErrorCode, number> = {
  [ErrorCode.INVALID_INPUT]: HttpStatus.BAD_REQUEST,
  [ErrorCode.OTP_INCORRECT]: HttpStatus.BAD_REQUEST,
  [ErrorCode.UNAUTHENTICATED]: HttpStatus.UNAUTHORIZED,
  [ErrorCode.FORBIDDEN]: HttpStatus.FORBIDDEN,
  [ErrorCode.NOT_FOUND]: HttpStatus.NOT_FOUND,
  [ErrorCode.FEE_ALREADY_PAID]: HttpStatus.CONFLICT,
  [ErrorCode.OTP_ALREADY_USED]: HttpStatus.CONFLICT,
  [ErrorCode.IDEMPOTENCY_CONFLICT]: HttpStatus.CONFLICT,
  [ErrorCode.OTP_EXPIRED]: HttpStatus.GONE,
  [ErrorCode.INSUFFICIENT_BALANCE]: HttpStatus.UNPROCESSABLE_ENTITY,
  [ErrorCode.TRANSACTION_INVALID_STATE]: HttpStatus.UNPROCESSABLE_ENTITY,
  [ErrorCode.RATE_LIMITED]: HttpStatus.TOO_MANY_REQUESTS,
  [ErrorCode.INTERNAL_ERROR]: HttpStatus.INTERNAL_SERVER_ERROR,
  [ErrorCode.DEPENDENCY_DOWN]: HttpStatus.SERVICE_UNAVAILABLE,
};
